// Generates dist/cjs/node-binance-api.d.cts, the type declarations for the
// CommonJS (`require`) entry of the package.
//
// The CJS bundle produced by rollup does `module.exports = Binance`, so its
// declarations must use `export =` rather than `export default`. Every other
// (type-only) export of the ESM entry is re-exposed through a namespace merged
// with the class, so CJS consumers can write `Binance.Order`, and
// `import type { Order } from 'node-binance-api'` keeps working.
//
// The export list is read from the emitted ESM declarations with the
// TypeScript compiler API, so new types in src/ are picked up automatically.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const esmDeclarationFile = path.join(rootDir, 'dist', 'node-binance-api.d.ts');
const cjsDeclarationFile = path.join(rootDir, 'dist', 'cjs', 'node-binance-api.d.cts');

if (!fs.existsSync(esmDeclarationFile)) {
    throw new Error(`${path.relative(rootDir, esmDeclarationFile)} not found, run tsc first`);
}

const program = ts.createProgram([esmDeclarationFile], {
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext,
    noEmit: true,
    skipLibCheck: true,
});
const checker = program.getTypeChecker();
const moduleSymbol = checker.getSymbolAtLocation(program.getSourceFile(esmDeclarationFile));

const typeAliases = [];
for (const exported of checker.getExportsOfModule(moduleSymbol)) {
    const name = exported.getName();
    if (name === 'default') {
        continue;
    }
    const target = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
    if (target.flags & ts.SymbolFlags.Value) {
        // A value export would also need to exist on the CJS `module.exports`
        // object, which rollup's "default" export mode does not provide.
        throw new Error(`Unsupported value export "${name}": only the default export may be a value`);
    }
    const declaration = target.declarations?.find((d) => d.typeParameters?.length);
    const typeParameters = declaration?.typeParameters ?? [];
    const params = typeParameters.length ? `<${typeParameters.map((p) => p.getText()).join(', ')}>` : '';
    const args = typeParameters.length ? `<${typeParameters.map((p) => p.name.getText()).join(', ')}>` : '';
    typeAliases.push(`    export type ${name}${params} = ESM.${name}${args};`);
}
typeAliases.sort();

const output = `// This file is generated by scripts/generate-cjs-types.mjs. Do not edit.
import type * as ESM from '../node-binance-api.js';

declare const Binance: typeof ESM.default;
type Binance = ESM.default;

declare namespace Binance {
${typeAliases.join('\n')}
}

export = Binance;
`;

fs.mkdirSync(path.dirname(cjsDeclarationFile), { recursive: true });
fs.writeFileSync(cjsDeclarationFile, output);
console.log(`Generated ${path.relative(rootDir, cjsDeclarationFile)} (${typeAliases.length} types)`);
