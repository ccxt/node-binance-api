// Generates the type declarations for the CommonJS (`require`) entry of the
// package, dist/cjs/node-binance-api.d.cts.
//
// The CJS bundle produced by rollup does `module.exports = Binance`, so its
// declarations must use `export =` rather than `export default`. Every other
// (type-only) export of the ESM entry is re-exposed through a namespace merged
// with the class, so CJS consumers can write `Binance.Order`, and
// `import type { Order } from 'node-binance-api'` keeps working.
//
// A CommonJS declaration file may not import an ES module declaration file
// under --module node16/node18 (or nodenext before TypeScript 5.8), so the
// emitted ESM declarations are first copied to dist/cjs/types/ as .d.cts files
// and the entry declaration imports those copies.
//
// The export list is read from the emitted ESM declarations with the
// TypeScript compiler API, so new types in src/ are picked up automatically.
// The result is type-checked (skipLibCheck off) before the script succeeds.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const distDir = path.join(rootDir, 'dist');
const cjsDir = path.join(distDir, 'cjs');
const cjsTypesDir = path.join(cjsDir, 'types');
const entryName = 'node-binance-api';
const esmEntryDeclaration = path.join(distDir, `${entryName}.d.ts`);
const cjsEntryDeclaration = path.join(cjsDir, `${entryName}.d.cts`);
const rel = (file) => path.relative(rootDir, file);

if (!fs.existsSync(esmEntryDeclaration)) {
    throw new Error(`${rel(esmEntryDeclaration)} not found, run tsc first`);
}

// 1. Copy dist/*.d.ts to dist/cjs/types/*.d.cts:
//    - point relative imports at the .cjs copies (`./x.cjs` maps to `./x.d.cts`);
//    - turn default imports of packages (e.g. `import WebSocket from 'ws'`) into
//      `import X = require('pkg')`, which unlike a default import of an
//      `export =` module also type-checks with esModuleInterop disabled.
fs.rmSync(cjsTypesDir, { recursive: true, force: true });
fs.mkdirSync(cjsTypesDir, { recursive: true });
for (const file of fs.readdirSync(distDir)) {
    if (!file.endsWith('.d.ts')) {
        continue;
    }
    const source = fs.readFileSync(path.join(distDir, file), 'utf8');
    const rewritten = source
        .replace(/(['"])(\.{1,2}\/[^'"]+)\.js\1/g, '$1$2.cjs$1')
        .replace(/^import (\w+) from (['"])([^.'"][^'"]*)\2;$/gm, 'import $1 = require($2$3$2);');
    fs.writeFileSync(path.join(cjsTypesDir, file.replace(/\.d\.ts$/, '.d.cts')), rewritten);
}

// 2. Collect the type exports of the ESM entry.
const program = ts.createProgram([esmEntryDeclaration], {
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext,
    noEmit: true,
    skipLibCheck: true,
});
const checker = program.getTypeChecker();
const moduleSymbol = checker.getSymbolAtLocation(program.getSourceFile(esmEntryDeclaration));

const typeAliases = [];
for (const exported of checker.getExportsOfModule(moduleSymbol)) {
    const name = exported.getName();
    if (name === 'default') {
        continue;
    }
    const isAlias = (exported.flags & ts.SymbolFlags.Alias) !== 0;
    const target = isAlias ? checker.getAliasedSymbol(exported) : exported;
    const isTypeOnlyExport = isAlias && checker.getTypeOnlyAliasDeclaration(exported) !== undefined;
    if ((target.flags & ts.SymbolFlags.Value) && !isTypeOnlyExport) {
        // A value export would also need to exist on the CJS `module.exports`
        // object, which rollup's "default" export mode does not provide.
        throw new Error(`Unsupported value export "${name}": only the default export may be a value`);
    }
    const declaration = target.declarations?.find((d) => d.typeParameters?.length);
    const typeParameters = declaration?.typeParameters ?? [];
    const params = typeParameters.length ? `<${typeParameters.map((p) => p.getText()).join(', ')}>` : '';
    const args = typeParameters.length ? `<${typeParameters.map((p) => p.name.getText()).join(', ')}>` : '';
    typeAliases.push(`    export type ${name}${params} = ESM.${name}${args};`);
}
typeAliases.sort();

// 3. Write the entry declaration.
fs.writeFileSync(cjsEntryDeclaration, `// This file is generated by scripts/generate-cjs-types.mjs. Do not edit.
import type * as ESM from './types/${entryName}.cjs';

declare const Binance: typeof ESM.default;
type Binance = ESM.default;

declare namespace Binance {
${typeAliases.join('\n')}
}

export = Binance;
`);

// 4. Type-check the generated declarations the way consumers will see them.
for (const mode of [ts.ModuleKind.Node16, ts.ModuleKind.NodeNext]) {
    for (const esModuleInterop of [true, false]) {
        const check = ts.createProgram([cjsEntryDeclaration], {
            module: mode,
            moduleResolution: mode === ts.ModuleKind.Node16 ? ts.ModuleResolutionKind.Node16 : ts.ModuleResolutionKind.NodeNext,
            esModuleInterop,
            allowSyntheticDefaultImports: esModuleInterop,
            strict: true,
            noEmit: true,
            skipLibCheck: false,
            types: [],
        });
        const diagnostics = ts.getPreEmitDiagnostics(check);
        if (diagnostics.length) {
            const host = { getCanonicalFileName: (f) => f, getCurrentDirectory: () => rootDir, getNewLine: () => '\n' };
            throw new Error(`Generated CJS declarations do not type-check (module ${ts.ModuleKind[mode]}, esModuleInterop ${esModuleInterop}):\n`
                + ts.formatDiagnostics(diagnostics, host));
        }
    }
}

console.log(`Generated ${rel(cjsEntryDeclaration)} (${typeAliases.length} types)`);
